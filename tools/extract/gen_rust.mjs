#!/usr/bin/env node
// Turns the extracted JSON tables into Rust source (tables.rs) that the
// gx100-protocol crate `include!`s at build time. No JSON parsing happens in Rust.
//
// usage: node tools/extract/gen_rust.mjs [inDir=extracted] [outFile=<inDir>/tables.rs] [--fixture]

import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const fixture = process.argv.includes('--fixture');
const inDir = path.resolve(args[0] || 'extracted');
const outFile = path.resolve(args[1] || path.join(inDir, 'tables.rs'));
const load = (f) => JSON.parse(fs.readFileSync(path.join(inDir, f), 'utf8'));

const product = load('product.json');
const commands = load('commands.json');
const { root } = load('address_map.blocks.json');
const flat = load('address_map.flat.json');
const { effects, master } = load('effects.json');
// Guide text (tools/extract/manual.mjs); optional.
const docs = fs.existsSync(path.join(inDir, 'docs.json')) ? load('docs.json') : { fx: [], params: [] };
const assign = fs.existsSync(path.join(inDir, 'assign.json')) ? load('assign.json') : { categories: [], targets: [] };
const paramValues = fs.existsSync(path.join(inDir, 'param_values.json')) ? load('param_values.json') : [];

// ---------------------------------------------------------------- literals
const str = (s) => '"' + String(s ?? '').replace(/[\\"]/g, (c) => '\\' + c)
  .replace(/[\u0000-\u001f\u007f]/g, (c) => `\\u{${c.charCodeAt(0).toString(16)}}`) + '"';
const wire = (hex) => {
  const b = hex.trim().split(/\s+/).map((x) => parseInt(x, 16));
  if (b.length !== 4 || b.some((x) => !(x >= 0 && x < 0x80))) throw new Error(`bad address ${hex}`);
  return `Address::from_wire([${b.map((x) => '0x' + x.toString(16).padStart(2, '0')).join(', ')}])`;
};
const linear = (hex) => { const b = hex.trim().split(/\s+/).map((x) => parseInt(x, 16)); return ((b[0] << 21) | (b[1] << 14) | (b[2] << 7) | b[3]) >>> 0; };
const int = (v, what) => { const n = Number(v); if (!Number.isInteger(n)) throw new Error(`${what}: not an integer: ${v}`); return n; };
const init = (v) => (v !== null && v !== undefined && String(v).trim() !== '' && Number.isInteger(Number(v)))
  ? `Init::Num(${Number(v)})` : `Init::Text(${str(v)})`;
const encoding = (e, bytes) => {
  const m = /^INTEGER1x([1-7])$/.exec(e);
  if (m) return `Encoding::Int1(${m[1]})`;
  switch (e) {
    case 'INTEGER2x4': return 'Encoding::Int2x4';
    case 'INTEGER2x7': return 'Encoding::Int2x7';
    case 'INTEGER4x4': return 'Encoding::Int4x4';
    case 'BYTES': return `Encoding::Bytes(${int(bytes, 'bytes')})`;
    case 'PADDING': return `Encoding::Padding(${int(bytes, 'bytes')})`;
    default: throw new Error(`unknown encoding ${e}`);
  }
};
const hexBytes = (h, n) => {
  const b = h.match(/../g).map((x) => parseInt(x, 16));
  if (b.length !== n) throw new Error(`expected ${n} bytes in ${h}`);
  return `[${b.map((x) => '0x' + x.toString(16).padStart(2, '0')).join(', ')}]`;
};

// ---------------------------------------------------------------- emit
const o = [];
o.push('// @generated by tools/extract/gen_rust.mjs — do not edit.');
o.push(fixture
  ? '// FIXTURE tables: synthetic, minimal, for tests only.'
  : '// Derived from BOSS TONE STUDIO for GX-100. Local use only — do not publish.');
o.push('');
o.push(`pub const SOURCE: TablesSource = TablesSource::${fixture ? 'Fixture' : 'Extracted'};`);
o.push('');
o.push('pub static PRODUCT: ProductDef = ProductDef {');
o.push(`    name: ${str(product.name)},`);
o.push(`    bts_version: ${str(product.btsVersion)},`);
o.push(`    bts_build: ${str(product.btsBuild)},`);
o.push(`    model_id: ${hexBytes(product.modelId, 5)},`);
o.push(`    device_id: 0x${product.deviceId},`);
o.push(`    communication_level: ${int(product.communicationLevel, 'communicationLevel')},`);
o.push(`    family_code: ${hexBytes(product.familyCode, 2)},`);
o.push('};');
o.push('');

const named = (obj) => Object.entries(obj).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([k, v]) => `    NamedAddress { name: ${str(k)}, addr: ${wire(v)} },`);
o.push('/// Special command addresses (sorted by name).');
o.push('pub static COMMANDS: &[NamedAddress] = &[', ...named(commands.commands), '];');
o.push('');
o.push('/// Fixed addresses the editor uses directly (sorted by name).');
o.push('pub static ADDRESSES: &[NamedAddress] = &[', ...named(commands.addresses), '];');
o.push('');

o.push('/// Top-level memory areas, in address order.');
o.push('pub static ROOT: &[RootDef] = &[');
for (const r of root) o.push(`    RootDef { name: ${str(r.name)}, block: ${str(r.block)}, addr: ${wire(r.addr)}, size: ${linear(r.size)} },`);
o.push('];');
o.push('');

const sortedFlat = [...flat].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
o.push('/// Every System / PC-map / Setup / Temp-patch parameter, sorted by path.');
o.push('pub static PARAMS: &[ParamDef] = &[');
for (const p of sortedFlat) {
  o.push(`    ParamDef { path: ${str(p.path)}, desc: ${str(p.desc)}, addr: ${wire(p.addr)}, encoding: ${encoding(p.encoding, p.bytes)}, ` +
    `min: ${int(p.min, p.path)}, max: ${int(p.max, p.path)}, init: ${init(p.init)}, ofs: ${int(p.ofs ?? 0, p.path)}, factor: ${int(p.factor ?? 1, p.path)} },`);
}
o.push('];');
o.push('');

const field = (p) => {
  if (p.paramIndex !== undefined) return `FxField::Param(${int(p.paramIndex, p.name)})`;
  if (p.field === 'Type' || p.field === 'Switch' || p.field === 'DuplicationNumber') return `FxField::${p.field}`;
  throw new Error(`fx param ${p.name}: no field`);
};
o.push('/// Value labels of list parameters, from the editor\'s UI definition (sorted by path).');
o.push('pub static PARAM_VALUES: &[ParamValues] = &[');
for (const v of paramValues) o.push(`    ParamValues { path: ${str(v.path)}, first: ${int(v.first, v.path)}, labels: &[${v.labels.map(str).join(', ')}] },`);
o.push('];');
o.push('');

// Labels in stored-value order. Where the editor lists them in another order (indexMachineValue),
// stored value v is labelled values[indexMachineValue[v]].
const valuesByMachine = (p) => {
  if (!Array.isArray(p.values)) return null;
  const imv = p.indexMachineValue;
  if (!imv) return p.values;
  if (imv.length !== p.values.length || [...imv].sort((a, b) => a - b).some((x, i) => x !== i))
    throw new Error(`fx param ${p.name}: indexMachineValue isn't a permutation of its labels`);
  return imv.map((pos) => p.values[pos]);
};
const fxType = (fx, id, indent) => {
  if (!fx.parameters) return [`${indent}FxTypeDef { id: ${id}, name: ${str(fx.name)}, params: &[] }`];
  const lines = [`${indent}FxTypeDef { id: ${id}, name: ${str(fx.name)}, params: &[`];
  for (const p of fx.parameters) {
    const v = valuesByMachine(p);
    const values = v ? `&[${v.map(str).join(', ')}]` : '&[]';
    lines.push(`${indent}    FxParamDef { name: ${str(p.name)}, unique_name: ${str(p.uniqueName)}, field: ${field(p)}, offset: ${wire(p.offsetInFxItem)}, ` +
      `encoding: ${encoding(p.encoding, p.bytes)}, min: ${int(p.min, p.name)}, max: ${int(p.max, p.name)}, init: ${init(p.init)}, ` +
      `ofs: ${int(p.ofs ?? 0, p.name)}, factor: ${int(p.factor ?? 1, p.name)}, values: ${values}, ` +
      `format: ${p.format ? `Some(${str(p.format)})` : 'None'}, template: ${str(p.template)} },`);
  }
  lines.push(`${indent}] }`);
  return lines;
};
o.push('/// FX types, indexed by the value of `fxItem(n).Type`.');
o.push('pub static FX_TYPES: &[FxTypeDef] = &[');
effects.forEach((fx, i) => {
  if (fx.typeId !== i) throw new Error(`fx type ${fx.name} out of order`);
  const lines = fxType(fx, i, '    ');
  lines[lines.length - 1] += ',';
  o.push(...lines);
});
o.push('];');
o.push('');

o.push('/// The patch\'s MASTER settings (level, BPM, key…) as assign targets see them. Offsets are meaningless.');
if (master && master.parameters) {
  const lines = fxType(master, 99, '');
  lines[0] = 'pub static MASTER: FxTypeDef = ' + lines[0];
  lines[lines.length - 1] += ';';
  o.push(...lines);
} else o.push('pub static MASTER: FxTypeDef = FxTypeDef { id: 99, name: "MASTER", params: &[] };');
o.push('');

o.push('/// Assign target categories, indexed by `AssignTargetDef::category`.');
o.push('pub static ASSIGN_CATEGORIES: &[AssignCategoryDef] = &[');
for (const c of assign.categories)
  o.push(`    AssignCategoryDef { name: ${str(c.name)}, has_switch: ${c.hasSwitch}, block_name: ${str(c.blockName)} },`);
o.push('];');
o.push('');
o.push('/// Assign targets, indexed by the value of `assign(n).TARGET`.');
o.push('pub static ASSIGN_TARGETS: &[AssignTargetDef] = &[');
for (const t of assign.targets)
  o.push(`    AssignTargetDef { name: ${str(t.name)}, category: ${int(t.category, t.name)}, effect: ${t.effect}, unique_name: ${str(t.uniqueName)} },`);
o.push('];');

o.push('');

const paramDoc = (d, indent) => `${indent}ParamDoc { key: ${str(d.key)}, text: ${str(d.text)}, options: &[` +
  d.options.map(([l, t]) => `(${str(l)}, ${str(t)})`).join(', ') + '] },';
o.push('/// The parameter guide\'s text about each FX type and its parameters.');
o.push('pub static FX_DOCS: &[FxDoc] = &[');
for (const f of docs.fx) {
  o.push(`    FxDoc { fx: ${str(f.fx)}, text: ${str(f.text)}, params: &[`);
  for (const d of f.params) o.push(paramDoc(d, '        '));
  o.push('    ] },');
}
o.push('];');
o.push('');
o.push('/// The parameter guide\'s text about patch and system settings, by generalized path (sorted).');
o.push('pub static PARAM_DOCS: &[ParamDoc] = &[');
for (const d of [...docs.params].sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0))) o.push(paramDoc(d, '    '));
o.push('];');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, o.join('\n') + '\n');
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${sortedFlat.length} params, ${effects.length} fx types)`);
